import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

public class RebuildDatabase {

    private static final String URL = env("DB_URL", "jdbc:postgresql://localhost:5432/iotdb");
    private static final String USER = env("DB_USER", "postgres");
    private static final String PASSWORD = env("DB_PASSWORD", "postgres");

    private static String env(String key, String fallback) {
        String value = System.getenv(key);
        return (value == null || value.isBlank()) ? fallback : value;
    }


    public static void main(String[] args) {

        String sql = """

                -- Drop all tables to start fresh
                DROP TABLE IF EXISTS sensor_readings CASCADE;
                DROP TABLE IF EXISTS sensors CASCADE;
                DROP TABLE IF EXISTS parking_spots CASCADE;
                DROP TABLE IF EXISTS parking_areas CASCADE;
                DROP TABLE IF EXISTS user_subscription CASCADE;
                DROP TABLE IF EXISTS subscription_plans CASCADE;
                DROP TABLE IF EXISTS users CASCADE;

                -- Users table
                CREATE TABLE users (
                    user_id    bigserial PRIMARY KEY,
                    email      varchar(255) NOT NULL UNIQUE,
                    first_name varchar(255),
                    last_name  varchar(255),
                    is_active  boolean DEFAULT TRUE NOT NULL,
                    created_at timestamp with time zone DEFAULT now() NOT NULL,
                    id         bigint generated by default as identity,
                    password   varchar(255) NOT NULL
                );

                -- Subscription Plans table
                CREATE TABLE subscription_plans (
                                                   plan_id BIGSERIAL PRIMARY KEY,
                                                   plan_name TEXT NOT NULL,
                                                   plan_code TEXT NOT NULL UNIQUE,
                                                   monthly_price DECIMAL NOT NULL,
                                                   description TEXT,
                                                   is_active BOOLEAN NOT NULL DEFAULT TRUE,
                                                   has_analytics BOOLEAN NOT NULL DEFAULT FALSE,
                                                   has_prediction BOOLEAN NOT NULL DEFAULT FALSE
                );

                -- User Subscriptions table
                CREATE TABLE user_subscription (
                                                   user_subscription_id BIGSERIAL PRIMARY KEY,
                                                   user_id BIGINT NOT NULL REFERENCES users(user_id),
                                                   plan_id BIGINT NOT NULL REFERENCES subscription_plans(plan_id),
                                                   status VARCHAR(50) NOT NULL,
                                                   start_date TIMESTAMP NOT NULL,
                                                   end_date TIMESTAMP,
                                                   locked_price DECIMAL NOT NULL,
                                                   locked_plan_name TEXT NOT NULL,
                                                   locked_plan_code TEXT NOT NULL,
                                                   has_analytics BOOLEAN NOT NULL,
                                                   has_prediction BOOLEAN NOT NULL
                );

                -- Parking Areas table
                CREATE TABLE parking_areas (
                    area_id bigserial PRIMARY KEY,
                    area_name text NOT NULL,
                    area_postcode text,
                    latitude double precision,
                    longitude double precision,
                    address text,
                    total_capacity integer CHECK (total_capacity >= 0),
                    area_type text,
                    is_active boolean DEFAULT TRUE NOT NULL
                );

                -- Parking Spots table
                CREATE TABLE parking_spots (
                    spot_id bigserial PRIMARY KEY,
                    area_id bigint NOT NULL REFERENCES parking_areas ON DELETE CASCADE,
                    spot_number integer NOT NULL,
                    is_operating boolean DEFAULT TRUE NOT NULL,
                    CONSTRAINT uq_area_spot UNIQUE (area_id, spot_number)
                );

                CREATE INDEX idx_spots_area ON parking_spots(area_id);

                -- Sensors table
                CREATE TABLE sensors (
                    sensor_id bigserial PRIMARY KEY,
                    spot_id bigint NOT NULL REFERENCES parking_spots ON DELETE CASCADE,
                    sensor_type text NOT NULL,
                    hardware_model text,
                    is_active boolean DEFAULT TRUE NOT NULL,
                    installed_at timestamp with time zone DEFAULT now()
                );

                CREATE INDEX idx_sensors_spot ON sensors(spot_id);

                -- Sensor Readings table (UPDATED)
                CREATE TABLE sensor_readings (
                    reading_id       bigserial PRIMARY KEY,
                    sensor_id        bigint NOT NULL REFERENCES sensors ON DELETE CASCADE,
                    reading_time     timestamp with time zone DEFAULT now() NOT NULL,
                    distance_mm      integer,
                    metal_detected   boolean,
                    occupied         boolean
                );

                CREATE INDEX idx_readings_sensor_time 
                    ON sensor_readings(sensor_id ASC, reading_time DESC);

                """;

        try (Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
             Statement stmt = conn.createStatement()) {

            stmt.execute(sql);
            System.out.println("DATABASE RECREATED SUCCESSFULLY!");

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
}
